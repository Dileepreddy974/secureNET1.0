test('beginner hash lab calculates MD5 and SHA-256, compares changes, and explains bytes', async ({ page }, info) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'TRY MD5 + SHA-256' }).click();
  await expect(page.getByRole('heading', { name: 'Make a digital fingerprint.' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'COMPARE FINGERPRINTS' })).toBeDisabled();
  await page.getByLabel('Original text', { exact: true }).fill('abc');
  await page.getByLabel('Changed text', { exact: true }).fill('abd');
  await page.getByRole('button', { name: 'CONNECT', exact: true }).click();
  await expect(page.getByText('CONNECTED + VERIFIED', { exact: true })).toBeVisible();
  await expect(page.getByLabel('Original text', { exact: true })).toHaveValue('abc');
  await page.getByRole('button', { name: 'COMPARE FINGERPRINTS' }).click();
  const md5 = page.getByRole('article', { name: 'MD5 results', exact: true });
  const sha256 = page.getByRole('article', { name: 'SHA-256 results', exact: true });
  await expect(md5.locator('.original-digest')).toHaveText('900150983cd24fb0d6963f7d28e17f72');
  await expect(sha256.locator('.original-digest')).toHaveText('ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad');
  expect(await sha256.locator('.hash-difference').count()).toBeGreaterThan(0);
  await page.getByRole('button', { name: '02 Computer bytes' }).click();
  await expect(page.locator('.hash-byte-views')).toContainText('61 62 63');
  await expect(page.locator('.hash-byte-views')).toContainText('61 62 64');
  await page.screenshot({ path: info.outputPath('hashing.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'USE THE SAME TEXT' }).click();
  await expect(page.locator('.hash-card')).toHaveCount(0);
  await page.getByRole('button', { name: 'COMPARE FINGERPRINTS' }).click();
  await expect(md5.getByRole('progressbar')).toHaveAttribute('value', '0');
  await expect(sha256.getByRole('progressbar')).toHaveAttribute('value', '0');
  await page.getByLabel('Original text', { exact: true }).fill('');
  await page.getByLabel('Changed text', { exact: true }).fill('');
  await page.getByRole('button', { name: 'COMPARE FINGERPRINTS' }).click();
  await expect(md5.locator('.original-digest')).toHaveText('d41d8cd98f00b204e9800998ecf8427e');
  await expect(page.getByText('A hash cannot be decrypted back into your text. It does not keep the text secret.')).toBeVisible();
  await page.getByRole('button', { name: 'Disconnect session' }).click();
});

import { test, expect } from '@playwright/test';

test('real messaging, playback, key rotation, and responsive layout', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.text().includes('Content Security Policy')) errors.push(message.text()); });
  await page.goto('/');
  await expect(page.getByRole('heading', { level: 1 })).toContainText('PRIVATE DATA.');
  await page.screenshot({ path: info.outputPath('initial.png'), fullPage: true });
  await page.getByRole('button', { name: 'CONNECT', exact: true }).click();
  await expect(page.getByText('CONNECTED + VERIFIED', { exact: true })).toBeVisible();
  await expect(page.getByText('LIVE EVENT FEED', { exact: true })).toBeVisible();
  await page.getByLabel('Your readable message').fill('Hello from the browser 🔒');
  await page.getByRole('button', { name: 'ENCRYPT + SEND', exact: true }).click();
  await expect(page.locator('.received-message')).toContainText('Hello from the browser 🔒');
  await expect(page.getByText('MESSAGE CHECK PASSED', { exact: true })).toBeVisible();
  await expect(page.locator('.record-list').first()).toContainText('000001');
  await page.getByRole('button', { name: '01 Text to bytes' }).click();
  await expect(page.locator('.pipeline-details')).toContainText('UTF-8');
  await expect(page.locator('.stage-evidence')).toContainText('48 65 6c 6c 6f');
  await expect(page.locator('.received-message')).not.toContainText('Hello from the browser 🔒');
  await page.getByRole('button', { name: '05 Unlock' }).click();
  await expect(page.locator('.received-message')).toContainText('Hello from the browser 🔒');
  await page.getByLabel('Encryption algorithm').selectOption('ChaCha20-Poly1305');
  await page.getByRole('button', { name: 'NEW SESSION', exact: true }).click();
  await expect(page.locator('.wire-label')).toHaveText('ChaCha20-Poly1305');
  await page.getByRole('button', { name: 'ENCRYPT + SEND', exact: true }).click();
  await expect(page.locator('.received-message')).toContainText('Hello from the browser 🔒');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  await page.screenshot({ path: info.outputPath('verified.png'), fullPage: true });
  await page.getByRole('button', { name: 'Disconnect session' }).click();
  await expect(page.getByText('NOT CONNECTED', { exact: true })).toBeVisible();
});

test('file integrity, attack demonstrations, measured benchmarks, and session isolation', async ({ page, browser }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'CONNECT', exact: true }).click();
  await expect(page.getByText('CONNECTED + VERIFIED', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'files', exact: true }).click();
  await page.getByLabel('Choose file').setInputFiles({ name: 'sample.bin', mimeType: 'application/octet-stream', buffer: Buffer.from('actual binary transfer\0\xff'.repeat(10000)) });
  await page.getByRole('button', { name: 'ENCRYPT + TRANSFER' }).click();
  await expect(page.getByText('Byte for byte. An exact match.')).toBeVisible();
  const hashes = await page.locator('.hash-list dd').allTextContents();
  expect(hashes[0]).toEqual(hashes[1]);
  const link = page.getByRole('link', { name: 'DOWNLOAD VERIFIED FILE' });
  const privatePath = await link.getAttribute('href');
  const stranger = await browser.newContext();
  expect((await stranger.request.get(`http://127.0.0.1:8001${privatePath}`)).status()).toBe(401);
  await stranger.close();
  const downloadPromise = page.waitForEvent('download');
  await link.click();
  expect((await downloadPromise).suggestedFilename()).toBe('sample.bin');
  await page.getByRole('button', { name: 'attacks', exact: true }).click();
  for (const action of ['TAMPER WITH RECORD', 'REPLAY A RECORD', 'SUBSTITUTE A KEY']) {
    await page.getByRole('button', { name: action, exact: true }).click();
    await expect(page.getByText('ATTACK REJECTED.', { exact: true })).toBeVisible();
  }
  await page.getByRole('button', { name: 'benchmarks', exact: true }).click();
  await page.getByRole('button', { name: 'RUN BENCHMARK' }).click();
  await expect(page.locator('tbody tr')).toHaveCount(6);
  await expect(page.getByRole('button', { name: 'EXPORT CSV' })).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Disconnect session' }).click();
});

